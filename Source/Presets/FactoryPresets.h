#pragma once
#include "SoundState.h"

namespace glitchkid
{
// Code-defined factory presets: lists of parameter overrides applied on top of the Factory Default sound, so every sound parameter is
// always set and a preset sounds the same whatever the plug-in was doing before. They use only existing parameters and effects.
// There are 50 artist-inspired presets (25 international, 25 Indian DHH). The artist is a reference label ONLY: these are original production-style
// starting points described by what they do to a vocal. They are not official, not licensed and not recreations of anyone's voice or recording chain.
// The table is generated by tools/gen_artist_presets.py into ArtistPresets.inc; saved sound never stores the names.
namespace FactoryPresets
{
    constexpr int count = 50;

    enum class Region { international, dhh };

    // Style tags (bit flags). A preset can have several.
    enum Tag : unsigned
    {
        melodicRap = 1, hardcoreLyrical = 2, trap = 4, drill = 8, rageDistorted = 16, rbPopRap = 32, experimental = 64, punjabi = 128, hindiUrdu = 256
    };
    constexpr int numTags = 9;
    const char* tagName (int bitIndex);                                 // "Melodic Rap", ... (bitIndex 0..numTags-1)

    struct Info
    {
        const char* name;        // shown in the preset menu and the preset bar, e.g. "TRAVIS SCOTT STYLE"
        const char* artist;      // the reference label, e.g. "Travis Scott"
        Region region;
        unsigned tags;           // Tag flags
        const char* description; // the intended character, in plain words
        const char* settings;    // what the preset actually does (generated from its values)
        const char* startWith;   // a suggested starting point for the user's vocal
    };

    const Info& info (int index);                                       // index 0..count-1
    int indexOfName (const juce::String& name);                         // case-insensitive; -1 if not a factory preset
    SoundState build (int index, const SoundState& factoryDefault);     // defaults + this preset's overrides
    struct Override { const char* id; float value; };
    int numOverrides (int index);
    const Override* overrides (int index);
    juce::String tagList (unsigned tags);                               // "Melodic Rap, Trap"
}
}
